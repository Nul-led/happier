/**
 * The one copy owner for "how do we know this file changed, and how sure are we".
 *
 * Every Changed Files surface — the attributed list, the review pane, the Git commit tab and the
 * evidence disclosure itself — reads these words through `t('changedFileEvidence.*')`, so the
 * vocabulary lives here rather than in each locale file. The qualification ("best-effort",
 * "no overlap observed") is the entire value of the disclosure: a locale that renders it in
 * English hides the one sentence a person needs to judge whether to trust the diff, which is why
 * every locale below is a real translation rather than a shared English placeholder.
 */
